package com.kragnoth.workbenchwisdom;

import com.mojang.serialization.MapCodec;
import com.mojang.serialization.codecs.RecordCodecBuilder;
import net.minecraft.core.HolderLookup;
import net.minecraft.core.NonNullList;
import net.minecraft.network.RegistryFriendlyByteBuf;
import net.minecraft.network.codec.StreamCodec;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.item.crafting.Ingredient;
import net.minecraft.world.item.crafting.Recipe;
import net.minecraft.world.item.crafting.RecipeSerializer;
import net.minecraft.world.item.crafting.RecipeType;
import net.minecraft.world.level.Level;

/**
 * Salvage at the Reforging Bench: a piece of gear on its own gives back {@code result}, the most it ever gives (when
 * unworn); worn gear gives less, in proportion ({@link #yield}). Generated by {@link Salvage}; datapacks can add more.
 */
public record SalvageRecipe(Ingredient input, ItemStack result) implements Recipe<ReforgingInput> {
    @Override
    public boolean matches(ReforgingInput in, Level level) {
        return in.addition().isEmpty() && in.base().getCount() == 1 && input.test(in.base());
    }

    /**
     * What this particular item gives: the full result scaled by how much of its durability is left, to the nearest
     * whole item (a single netherite ingot comes back while the gear is at least half whole).
     */
    public ItemStack salvageOf(ItemStack gear) {
        int n = result.getCount();
        if (gear.isDamageableItem() && gear.getMaxDamage() > 0) {
            n = (int) Math.round(n * (gear.getMaxDamage() - gear.getDamageValue()) / (double) gear.getMaxDamage());
        }
        return n <= 0 ? ItemStack.EMPTY : result.copyWithCount(n);
    }

    @Override
    public ItemStack assemble(ReforgingInput in, HolderLookup.Provider registries) {
        return salvageOf(in.base());
    }

    @Override
    public boolean canCraftInDimensions(int width, int height) {
        return true;
    }

    @Override
    public ItemStack getResultItem(HolderLookup.Provider registries) {
        return result;
    }

    @Override
    public NonNullList<Ingredient> getIngredients() {
        return NonNullList.of(Ingredient.EMPTY, input);
    }

    @Override
    public boolean isSpecial() {
        return true;
    }

    @Override
    public RecipeSerializer<?> getSerializer() {
        return WorkbenchWisdom.SALVAGE_SERIALIZER.get();
    }

    @Override
    public RecipeType<?> getType() {
        return WorkbenchWisdom.SALVAGE.get();
    }

    private static final MapCodec<SalvageRecipe> CODEC = RecordCodecBuilder.mapCodec(i -> i.group(
            Ingredient.CODEC_NONEMPTY.fieldOf("input").forGetter(SalvageRecipe::input),
            ItemStack.STRICT_CODEC.fieldOf("result").forGetter(SalvageRecipe::result)
    ).apply(i, SalvageRecipe::new));

    private static final StreamCodec<RegistryFriendlyByteBuf, SalvageRecipe> STREAM_CODEC = StreamCodec.composite(
            Ingredient.CONTENTS_STREAM_CODEC, SalvageRecipe::input,
            ItemStack.STREAM_CODEC, SalvageRecipe::result,
            SalvageRecipe::new);

    static final RecipeSerializer<SalvageRecipe> SERIALIZER = new RecipeSerializer<>() {
        @Override
        public MapCodec<SalvageRecipe> codec() {
            return CODEC;
        }

        @Override
        public StreamCodec<RegistryFriendlyByteBuf, SalvageRecipe> streamCodec() {
            return STREAM_CODEC;
        }
    };
}
