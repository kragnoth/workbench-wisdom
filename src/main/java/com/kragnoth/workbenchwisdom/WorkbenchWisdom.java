package com.kragnoth.workbenchwisdom;

import com.mojang.logging.LogUtils;
import net.minecraft.core.registries.Registries;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.world.flag.FeatureFlags;
import net.minecraft.world.inventory.MenuType;
import net.minecraft.world.item.BlockItem;
import net.minecraft.world.item.CreativeModeTabs;
import net.minecraft.world.item.crafting.RecipeSerializer;
import net.minecraft.world.item.crafting.RecipeType;
import net.minecraft.world.level.block.SoundType;
import net.minecraft.world.level.block.state.BlockBehaviour;
import net.minecraft.world.level.block.state.properties.NoteBlockInstrument;
import net.minecraft.world.level.material.MapColor;
import net.neoforged.neoforge.registries.DeferredBlock;
import net.neoforged.neoforge.registries.DeferredItem;
import net.neoforged.bus.api.IEventBus;
import net.neoforged.fml.ModContainer;
import net.neoforged.fml.common.Mod;
import net.neoforged.fml.config.ModConfig;
import net.neoforged.neoforge.registries.DeferredHolder;
import net.neoforged.neoforge.registries.DeferredRegister;
import org.slf4j.Logger;

/**
 * Workbench Wisdom: three crafting conveniences, all data-driven and configurable.
 * <ul>
 *   <li>The Reforging Bench ({@link ReforgingMenu}): tier upgrades for tools and armour that keep their enchantments
 *       ({@link ReforgingRecipe}, generated by {@link TierUpgrades} from item names across every mod), and moving
 *       enchantments from one tool or armour piece onto another ({@link EnchantTransfer}).</li>
 *   <li>{@link StonecutterTweaks}: every stonecutter recipe makes one item and can be cut back the other way.</li>
 * </ul>
 */
@Mod(WorkbenchWisdom.MODID)
public class WorkbenchWisdom {
    public static final String MODID = "workbenchwisdom";
    public static final Logger LOG = LogUtils.getLogger();

    public static final DeferredRegister<RecipeSerializer<?>> SERIALIZERS = DeferredRegister.create(Registries.RECIPE_SERIALIZER, MODID);
    public static final DeferredRegister<RecipeType<?>> RECIPE_TYPES = DeferredRegister.create(Registries.RECIPE_TYPE, MODID);
    public static final DeferredRegister<MenuType<?>> MENUS = DeferredRegister.create(Registries.MENU, MODID);
    public static final DeferredRegister.Blocks BLOCKS = DeferredRegister.createBlocks(MODID);
    public static final DeferredRegister.Items ITEMS = DeferredRegister.createItems(MODID);

    public static final DeferredHolder<RecipeType<?>, RecipeType<ReforgingRecipe>> REFORGING =
            RECIPE_TYPES.register("reforging", () -> RecipeType.simple(ResourceLocation.fromNamespaceAndPath(MODID, "reforging")));
    public static final DeferredHolder<RecipeSerializer<?>, RecipeSerializer<ReforgingRecipe>> REFORGING_SERIALIZER =
            SERIALIZERS.register("reforging", () -> ReforgingRecipe.SERIALIZER);
    public static final DeferredHolder<RecipeType<?>, RecipeType<SalvageRecipe>> SALVAGE =
            RECIPE_TYPES.register("salvage", () -> RecipeType.simple(ResourceLocation.fromNamespaceAndPath(MODID, "salvage")));
    public static final DeferredHolder<RecipeSerializer<?>, RecipeSerializer<SalvageRecipe>> SALVAGE_SERIALIZER =
            SERIALIZERS.register("salvage", () -> SalvageRecipe.SERIALIZER);
    public static final DeferredHolder<MenuType<?>, MenuType<ReforgingMenu>> REFORGING_MENU =
            MENUS.register("reforging_bench", () -> new MenuType<>(ReforgingMenu::new, FeatureFlags.VANILLA_SET));
    public static final DeferredBlock<ReforgingBenchBlock> REFORGING_BENCH = BLOCKS.registerBlock("reforging_bench", ReforgingBenchBlock::new,
            BlockBehaviour.Properties.of().mapColor(MapColor.WOOD).instrument(NoteBlockInstrument.BASS).strength(2.5F).sound(SoundType.WOOD));
    public static final DeferredItem<BlockItem> REFORGING_BENCH_ITEM = ITEMS.registerSimpleBlockItem(REFORGING_BENCH);

    public WorkbenchWisdom(IEventBus modBus, ModContainer container) {
        SERIALIZERS.register(modBus);
        RECIPE_TYPES.register(modBus);
        MENUS.register(modBus);
        BLOCKS.register(modBus);
        ITEMS.register(modBus);
        modBus.addListener((net.neoforged.neoforge.event.BuildCreativeModeTabContentsEvent e) -> {
            if (e.getTabKey() == CreativeModeTabs.FUNCTIONAL_BLOCKS) {
                e.accept(REFORGING_BENCH_ITEM.get());
            }
        });
        container.registerConfig(ModConfig.Type.COMMON, Config.SPEC);
    }
}
